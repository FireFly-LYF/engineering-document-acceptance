"""Generate explicit MySQL FKs from the executable local schema; no server mutation."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

SHORT = {'id','bundle_id','code','label_code','tag_code','project_id','parent_id','scope_id',
    'run_id','source_file_id','document_unit_id','markdown_unit_id','fragment_id','evidence_id',
    'candidate_id','evaluation_id','finding_id','decision_id','kind','stage','value_type','comparison_scope',
    'source_type','status','parse_status','parse_error_code','tag_origin','tag_status','identity_status',
    'scope_status','read_status','grounding_status','value_role','source','validation_status',
    'purpose','rule_code','result','applicability','severity','finding_type','relation','decision',
    'error_code','audit_stage','engine_version','fire_category','use_type','region_code','value_unit',
    'validation_status','table_id'}
DIGEST = {'sha256','input_sha256','config_sha256','text_sha256','prompt_sha256'}
DATE = {'created_at','applied_at','started_at','finished_at','valid_from','valid_to'}
INDEXED = {'relative_path':512, 'scope_key':128}


def generate():
    raw = (ROOT / 'database/schema.sqlite.sql').read_text(encoding='utf-8')
    tables = []
    for match in re.finditer(r'CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\n\);', raw, re.S):
        name, body = match.groups()
        def column(m):
            key = m.group(1)
            if key in DATE:
                typ = 'DATETIME'
            elif key.endswith('_json'):
                typ = 'JSON'
            elif key in DIGEST:
                typ = 'CHAR(64)'
            elif key in INDEXED:
                typ = f'VARCHAR({INDEXED[key]})'
            elif key in SHORT:
                typ = 'VARCHAR(64)'
            elif key in ('name','external_code','original_name','reason_code','reviewer_ref','model_name','mime_type','version'):
                typ = 'VARCHAR(255)'
            else:
                typ = 'LONGTEXT'
            return key + ' ' + typ
        body = re.sub(r'\b(\w+) TEXT\b', column, body)
        body = re.sub(r'\bREAL\b', 'DOUBLE', body)
        body = re.sub(r'\bINTEGER\b', 'BIGINT', body)
        inline_fks = []
        def inline(m):
            declaration, parent, parent_key = m.groups()
            key = declaration.split()[0]
            inline_fks.append(f'FOREIGN KEY({key}) REFERENCES {parent}({parent_key})')
            return declaration
        body = re.sub(r'(\b\w+\s+[^,\n]*?)\s+REFERENCES\s+(\w+)\((\w+)\)', inline, body)
        if inline_fks:
            body = body.rstrip() + ',\n  ' + ',\n  '.join(inline_fks)
        tables.append(f'CREATE TABLE IF NOT EXISTS {name} ({body}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;')
    if len(tables) != raw.count('CREATE TABLE IF NOT EXISTS'):
        raise ValueError('DDL conversion omitted a table')
    indexes = re.findall(r'CREATE INDEX IF NOT EXISTS (\w+) ON (\w+)\(([^)]+)\);', raw)
    for index, table, cols in indexes:
        # Inline indexes make the generated schema idempotent through CREATE TABLE.
        for i, text in enumerate(tables):
            if text.startswith('CREATE TABLE IF NOT EXISTS ' + table + ' '):
                tables[i] = text.replace('\n) ENGINE=', f',\n  INDEX {index} ({cols})\n) ENGINE=')
                break
    header = '-- Generated by tools/build_mysql_schema.py. Target: MySQL 8.0.16+ (CHECK enforcement).\n-- No CREATE DATABASE, DROP, or credentials. Review before applying to an existing service.\n'
    output = header + '\n\n'.join(tables) + '\nINSERT IGNORE INTO schema_migration(version) VALUES(1);\n'
    (ROOT / 'database/schema.mysql.sql').write_text(output, encoding='utf-8')
    return len(tables)


if __name__ == '__main__':
    print('Generated MySQL tables:', generate())
